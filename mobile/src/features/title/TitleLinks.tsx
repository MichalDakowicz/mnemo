function Mark({ label, url, children }: { label: string; url: string; children: ReactNode }) {
  return (
    <Pressable
      accessibilityRole="link"
      accessibilityLabel={label}
      hitSlop={10}
      onPress={() => void Linking.openURL(url)}
      style={({ pressed }) => [styles.mark, pressed && { opacity: 0.6 }]}>
      {children}
    </Pressable>
  );
}

